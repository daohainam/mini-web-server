using MiniWebServer.Server.ProtocolHandlers.Http2;
using System.Buffers;

namespace Http2Tests;

public class Http2FramePayloadReaderTests
{
    private static void AssertHeader(HPACKHeader header, string name, string value)
    {
        Assert.Equal(name, header.Name);
        Assert.Equal(value, header.Value);
    }

    [Fact]
    public void TryReadHEADERSFramePayload_ValidPayload_ReturnsTrueAndHeadersPayload()
    {
        // Arrange
        var frame = new Http2Frame { FrameType = Http2FrameType.HEADERS, Flags = Http2FrameFlags.END_HEADERS };
        var payload = new ReadOnlySequence<byte>([0x82, 0x86, 0x84, 0x41, 0x8c, 0xf1, 0xe3, 0xc2, 0xe5, 0xf2, 0x3a, 0x6b, 0xa0, 0xab, 0x90, 0xf4, 0xff]);
        var decoder = new HPACKDecoder();

        // Act
        var result = Http2FrameReader.TryReadHEADERSFramePayload(frame, payload, out var headersPayload);
        var headers = decoder.Decode(headersPayload.FieldBlockFragment);

        // Assert
        Assert.True(result);
        Assert.Equal(payload.Length, headersPayload.FieldBlockFragment.Length);
        Assert.Equal(4, headers.Count);
        AssertHeader(headers[0], ":method", "GET");
        AssertHeader(headers[1], ":scheme", "http");
        AssertHeader(headers[2], ":path", "/");
        AssertHeader(headers[3], ":authority", "www.example.com");
    }

    [Fact]
    public void TryReadHEADERSFramePayload_PaddedAndPriority_StripsBothBeforeTheFieldBlock()
    {
        // Arrange: PADDED | PRIORITY, pad length 3, stream dependency 0x7 exclusive, weight 16, block = indexed :method GET, 3 bytes padding
        var frame = new Http2Frame { FrameType = Http2FrameType.HEADERS, Flags = Http2FrameFlags.END_HEADERS | Http2FrameFlags.PADDED | Http2FrameFlags.PRIORITY };
        var payload = new ReadOnlySequence<byte>([0x03, 0x80, 0x00, 0x00, 0x07, 0x10, 0x82, 0x00, 0x00, 0x00]);

        // Act
        var result = Http2FrameReader.TryReadHEADERSFramePayload(frame, payload, out var headersPayload);

        // Assert
        Assert.True(result);
        Assert.Equal(3, headersPayload.PadLength);
        Assert.True(headersPayload.HasPriority);
        Assert.True(headersPayload.Exclusive);
        Assert.Equal(7u, headersPayload.StreamDependency);
        Assert.Equal(16, headersPayload.Weight);
        Assert.Equal(new byte[] { 0x82 }, headersPayload.FieldBlockFragment.ToArray());
    }

    [Fact]
    public void TryReadHEADERSFramePayload_PaddingLongerThanPayload_ReturnsFalse()
    {
        var frame = new Http2Frame { FrameType = Http2FrameType.HEADERS, Flags = Http2FrameFlags.PADDED };
        var payload = new ReadOnlySequence<byte>([0x05, 0x82, 0x00]);

        Assert.False(Http2FrameReader.TryReadHEADERSFramePayload(frame, payload, out _));
    }

    [Fact]
    public void TryReadDATAFramePayload_Padded_StripsPadding()
    {
        // from http2jp test cases: pad length 6, "Hello, world!" followed by "Howdy!" as padding
        var frame = new Http2Frame { FrameType = Http2FrameType.DATA, Flags = Http2FrameFlags.PADDED };
        var payload = new ReadOnlySequence<byte>("0648656C6C6F2C20776F726C6421486F77647921".ToByteArray());

        var result = Http2FrameReader.TryReadDATAFramePayload(frame, payload, out var data);

        Assert.True(result);
        Assert.Equal("Hello, world!", System.Text.Encoding.ASCII.GetString(data.ToArray()));
    }

    [Fact]
    public void TryReadDATAFramePayload_PadLengthNotSmallerThanPayload_ReturnsFalse()
    {
        var frame = new Http2Frame { FrameType = Http2FrameType.DATA, Flags = Http2FrameFlags.PADDED };
        var payload = new ReadOnlySequence<byte>([0x03, 0x41, 0x42]);

        Assert.False(Http2FrameReader.TryReadDATAFramePayload(frame, payload, out _));
    }

    [Fact]
    public void TryReadRST_STREAMFramePayload_ReadsErrorCode()
    {
        var payload = new ReadOnlySequence<byte>([0x00, 0x00, 0x00, 0x08]);

        Assert.True(Http2FrameReader.TryReadRST_STREAMFramePayload(ref payload, out var errorCode));
        Assert.Equal(Http2ErrorCode.CANCEL, errorCode);
    }

    [Fact]
    public void TryReadGOAWAYFramePayload_ReadsLastStreamIdErrorCodeAndDebugData()
    {
        var payload = new ReadOnlySequence<byte>("0000001E00000009687061636B2069732062726F6B656E".ToByteArray());

        Assert.True(Http2FrameReader.TryReadGOAWAYFramePayload(ref payload, out var lastStreamId, out var errorCode, out var debugData));
        Assert.Equal(30u, lastStreamId);
        Assert.Equal(Http2ErrorCode.COMPRESSION_ERROR, errorCode);
        Assert.Equal("hpack is broken", System.Text.Encoding.ASCII.GetString(debugData.ToArray()));
    }

    [Fact]
    public void TryReadHEADERSFramePayload_LongValidPayload_1_ReturnsTrueAndHeadersPayload()
    {
        // Arrange
        var frame = new Http2Frame();
        var buffer = new ReadOnlySequence<byte>([0x0, 0x0, 0x27, 0x1, 0x5, 0x0, 0x0, 0x0, 0x1, 0x82, 0x86, 0x1, 0xe, 0x6c, 0x6f, 0x63, 0x61, 0x6c, 0x68, 0x6f, 0x73, 0x74, 0x3a, 0x39, 0x36, 0x35, 0x32, 0x84, 0xf, 0x1, 0x11, 0x67, 0x7a, 0x69, 0x70, 0x2c, 0x20, 0x64, 0x65, 0x66, 0x6c, 0x61, 0x74, 0x65, 0x2c, 0x20, 0x62, 0x72]);
        var decoder = new HPACKDecoder();
        var maxFrameSize = 1024u;

        // Act
        var result = Http2FrameReader.TryReadFrame(ref buffer, ref frame, maxFrameSize, out ReadOnlySequence<byte> payload);

        // Assert
        Assert.True(result);
        Assert.Equal(Http2FrameType.HEADERS, frame.FrameType);
        Assert.Equal(Http2FrameFlags.END_STREAM | Http2FrameFlags.END_HEADERS, frame.Flags);
        Assert.Equal(39, frame.Length);
        Assert.Equal(1u, frame.StreamIdentifier);
        Assert.Equal(frame.Length, payload.Length);

        result = Http2FrameReader.TryReadHEADERSFramePayload(frame, payload, out var headersPayload);
        var headers = decoder.Decode(headersPayload.FieldBlockFragment);

        // Assert
        Assert.True(result);
        Assert.Equal(5, headers.Count);
        AssertHeader(headers[0], ":method", "GET");
        AssertHeader(headers[1], ":scheme", "http");
        AssertHeader(headers[2], ":authority", "localhost:9652");
        AssertHeader(headers[3], ":path", "/");
        AssertHeader(headers[4], "accept-encoding", "gzip, deflate, br");
    }

